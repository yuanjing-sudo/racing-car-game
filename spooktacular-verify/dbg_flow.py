import pathlib, re
root = pathlib.Path('spooktacular-halloween-app/Sources/Ultimate')
qu = (root / 'MineQuests.swift').read_text(encoding='utf-8')
am = (root / 'AbandonedMine.swift').read_text(encoding='utf-8')
me = (root / 'MazeExpeditions.swift').read_text(encoding='utf-8')
tm = (root / 'TunnelMaze.swift').read_text(encoding='utf-8')
produced_q = set(re.findall(r'questBoard\.record\(\.(\w+)', am))
i = qu.find('private func advance')
print('advance idx:', i, 'len:', len(qu))
handled_q = set(re.findall(r'\(\.\w+,\s*\.(\w+)\)', qu[i:i + 12000]))
print('PRODUCED Q:', sorted(produced_q))
print('HANDLED Q:', sorted(handled_q))
j = me.find('private func advance')
print('exp advance idx:', j, 'len:', len(me))
handled_e = set(re.findall(r'\(\.\w+,\s*\.(\w+)\)', me[j:j + 8000]))
produced_e = set(re.findall(r'expeditionBoard\.record\(\.(\w+)', tm))
print('PRODUCED E:', sorted(produced_e))
print('HANDLED E:', sorted(handled_e))
